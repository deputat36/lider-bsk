 SET search_path TO ''
AS $function$
declare
  v_actor_id uuid;
  v_request jsonb;
  v_request_id uuid;
  v_expected_updated_at timestamptz;
  v_payload jsonb;
  v_normalized_payload jsonb;
  v_action text;
  v_calculation_id uuid;
  v_idempotency_key text;
  v_title text;
  v_valid_until date;
  v_extra_comment text;
  v_profile public.leader_user_profiles%rowtype;
  v_calculation public.leader_lead_calculations%rowtype;
  v_item public.leader_lead_calculation_items%rowtype;
  v_lead public.leader_leads%rowtype;
  v_need public.leader_lead_needs%rowtype;
  v_offer public.leader_commercial_offers%rowtype;
  v_event public.leader_commercial_offer_events%rowtype;
  v_receipt leader_private.leader_command_receipts%rowtype;
  v_existing_receipt leader_private.leader_command_receipts%rowtype;
  v_request_hash text;
  v_canonical jsonb;
  v_response jsonb;
  v_lead_json jsonb;
  v_need_json jsonb := '{}'::jsonb;
  v_calculation_json jsonb;
  v_lead_name text;
  v_lead_phone text;
  v_lead_service text;
  v_need_text text;
  v_short_items text := '';
  v_full_items text := '';
  v_short_text text;
  v_full_text text;
  v_public_total numeric := 0;
  v_item_count integer := 0;
  v_money text;
  v_qty text;
  v_now timestamptz;
  v_constraint_name text;
  v_exception_state text;
begin
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    return jsonb_build_object('ok', false, 'request_id', null,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'RPC payload must be an object'));
  end if;

  if exists (
    select 1 from jsonb_object_keys(p_payload) as k(key)
    where key not in ('actor_id', 'actor_email', 'request')
  ) then
    return jsonb_build_object('ok', false, 'request_id', null,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Unknown RPC payload field'));
  end if;

  begin
    v_actor_id := nullif(btrim(p_payload ->> 'actor_id'), '')::uuid;
  exception when others then
    return jsonb_build_object('ok', false, 'request_id', null,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'actor_id must be UUID'));
  end;

  v_request := p_payload -> 'request';
  if v_actor_id is null or v_request is null or jsonb_typeof(v_request) <> 'object' then
    return jsonb_build_object('ok', false, 'request_id', null,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'actor_id and request are required'));
  end if;

  if exists (
    select 1 from jsonb_object_keys(v_request) as k(key)
    where key not in ('action', 'request_id', 'expected_updated_at', 'payload')
  ) then
    return jsonb_build_object('ok', false, 'request_id', null,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Unknown request field'));
  end if;

  v_action := btrim(v_request ->> 'action');
  if v_action <> 'offer.create_from_calculation' then
    return jsonb_build_object('ok', false, 'request_id', v_request ->> 'request_id',
      'error', jsonb_build_object('code', 'unknown_action', 'message', 'Unsupported action'));
  end if;

  begin
    v_request_id := nullif(btrim(v_request ->> 'request_id'), '')::uuid;
    v_expected_updated_at := nullif(btrim(v_request ->> 'expected_updated_at'), '')::timestamptz;
  exception when others then
    return jsonb_build_object('ok', false, 'request_id', v_request ->> 'request_id',
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'request_id or expected_updated_at is invalid'));
  end;

  v_payload := v_request -> 'payload';
  if v_request_id is null or v_expected_updated_at is null
     or v_payload is null or jsonb_typeof(v_payload) <> 'object' then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Request fields are required'));
  end if;

  if exists (
    select 1 from jsonb_object_keys(v_payload) as k(key)
    where key not in ('calculation_id', 'idempotency_key', 'title', 'valid_until', 'extra_comment')
  ) then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Unknown or server-owned business field'));
  end if;

  if jsonb_typeof(v_request -> 'action') <> 'string'
     or jsonb_typeof(v_request -> 'request_id') <> 'string'
     or jsonb_typeof(v_request -> 'expected_updated_at') <> 'string'
     or jsonb_typeof(v_payload -> 'calculation_id') <> 'string'
     or jsonb_typeof(v_payload -> 'idempotency_key') <> 'string'
     or jsonb_typeof(v_payload -> 'title') <> 'string'
     or jsonb_typeof(v_payload -> 'valid_until') <> 'string'
     or (
       v_payload ? 'extra_comment'
       and jsonb_typeof(v_payload -> 'extra_comment') not in ('string', 'null')
     ) then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Request field types are invalid'));
  end if;

  if (v_payload ->> 'valid_until') !~ '^\d{4}-\d{2}-\d{2}$' then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'valid_until must be YYYY-MM-DD'));
  end if;

