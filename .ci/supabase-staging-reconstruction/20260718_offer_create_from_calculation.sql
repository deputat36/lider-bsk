    v_item_count := v_item_count + 1;
    v_public_total := v_public_total + v_item.client_sum;
    v_money := trim(to_char(round(v_item.client_sum, 2), 'FM999999999990.00')) || ' ₽';
    v_qty := trim(to_char(v_item.qty, 'FM999999999990.###'));
    v_short_items := v_short_items || E'\n— ' || v_item.name;
    v_full_items := v_full_items || E'\n— ' || v_item.name
      || ' — ' || v_qty || case when nullif(btrim(coalesce(v_item.unit, '')), '') is null then '' else ' ' || btrim(v_item.unit) end
      || ' — ' || v_money;
  end loop;

