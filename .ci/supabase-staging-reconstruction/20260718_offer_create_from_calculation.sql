  from public.leader_leads
  where id = v_calculation.lead_id
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_calculation', 'message', 'Calculation lead was not found'));
  end if;

  if v_calculation.need_id is not null then
    select * into v_need
    from public.leader_lead_needs
    where id = v_calculation.need_id and lead_id = v_calculation.lead_id
    for share;
    if found then v_need_json := to_jsonb(v_need); end if;
  end if;

  for v_item in
    select *
    from public.leader_lead_calculation_items
    where calculation_id = v_calculation.id and client_sum > 0
    order by sort_order, created_at, id
    for share
