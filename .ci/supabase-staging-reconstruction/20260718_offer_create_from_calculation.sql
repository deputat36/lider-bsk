  if v_calculation_json ? 'is_current_revision'
     and coalesce((v_calculation_json ->> 'is_current_revision')::boolean, false) is not true then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'calculation_not_current', 'message', 'Offer can only be created from the current calculation revision'));
  end if;

  if v_calculation.commercial_offer_id is not null or exists (
    select 1 from public.leader_commercial_offers where calculation_id = v_calculation.id
  ) then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'offer_already_exists', 'message', 'An offer already exists for this calculation'));
  end if;

  if v_calculation.client_total <= 0 then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_calculation', 'message', 'Calculation client total must be positive'));
  end if;

