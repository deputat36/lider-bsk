    v_calculation_id := nullif(btrim(v_payload ->> 'calculation_id'), '')::uuid;
    v_valid_until := nullif(btrim(v_payload ->> 'valid_until'), '')::date;
  exception when others then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'calculation_id or valid_until is invalid'));
  end;

  v_idempotency_key := btrim(v_payload ->> 'idempotency_key');
  v_title := btrim(v_payload ->> 'title');
  v_extra_comment := nullif(btrim(v_payload ->> 'extra_comment'), '');

  if v_calculation_id is null
     or v_idempotency_key is null or char_length(v_idempotency_key) not between 1 and 160
     or v_title is null or char_length(v_title) not between 1 and 500
     or char_length(coalesce(v_extra_comment, '')) > 4000 then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_payload', 'message', 'Business payload is invalid'));
  end if;

  if v_valid_until is null or v_valid_until < current_date or v_valid_until > current_date + 730 then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'invalid_valid_until', 'message', 'valid_until must be within the next 730 days'));
  end if;

  select * into v_profile
  from public.leader_user_profiles
  where user_id = v_actor_id and is_active = true
  for share;

  if not found then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'inactive_profile', 'message', 'Active profile is required'));
  end if;

  if lower(btrim(v_profile.role)) not in ('owner', 'admin', 'manager') then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'forbidden', 'message', 'offers.write is required'));
  end if;

  v_normalized_payload := jsonb_build_object(
    'calculation_id', v_calculation_id,
    'idempotency_key', v_idempotency_key,
    'title', v_title,
    'valid_until', to_char(v_valid_until, 'YYYY-MM-DD'),
    'extra_comment', v_extra_comment
  );
