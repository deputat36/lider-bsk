    'action', v_action,
    'expected_updated_at', to_char(v_expected_updated_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
    'payload', v_normalized_payload,
    'actor_id', v_actor_id
  );
  v_request_hash := encode(extensions.digest(convert_to(v_canonical::text, 'UTF8'), 'sha256'), 'hex');

  perform pg_advisory_xact_lock(hashtextextended(v_action || ':receipt:' || v_idempotency_key, 0));

  select * into v_existing_receipt
  from leader_private.leader_command_receipts
  where action = v_action and idempotency_key = v_idempotency_key
  for update;

  if found then
    if v_existing_receipt.request_hash <> v_request_hash then
      return jsonb_build_object('ok', false, 'request_id', v_request_id,
        'error', jsonb_build_object('code', 'idempotency_conflict', 'message', 'Idempotency key was used with another payload'));
    end if;
    if v_existing_receipt.state = 'success' and v_existing_receipt.response is not null then
      return v_existing_receipt.response || jsonb_build_object('idempotent_replay', true);
    end if;
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'idempotency_conflict', 'message', 'Command is already in progress'));
  end if;

  if exists (
    select 1 from leader_private.leader_command_receipts
    where action = v_action and request_id = v_request_id
  ) then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'request_id_conflict', 'message', 'request_id was already used'));
  end if;

  select * into v_calculation
  from public.leader_lead_calculations
  where id = v_calculation_id
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'calculation_not_found', 'message', 'Calculation was not found'));
  end if;

  if v_calculation.updated_at is distinct from v_expected_updated_at then
    return jsonb_build_object('ok', false, 'request_id', v_request_id,
      'error', jsonb_build_object('code', 'calculation_changed', 'message', 'Calculation changed; reload before creating an offer'));
  end if;

