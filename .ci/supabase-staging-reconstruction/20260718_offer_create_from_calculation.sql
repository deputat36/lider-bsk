      'error', jsonb_build_object('code', 'invalid_calculation', 'message', 'Generated offer text exceeds safe limits'));
  end if;

  v_now := clock_timestamp();

  insert into leader_private.leader_command_receipts (
    action, idempotency_key, request_id, request_hash, actor_id, state
  ) values (
    v_action, v_idempotency_key, v_request_id, v_request_hash, v_actor_id, 'in_progress'
  ) returning * into v_receipt;

  insert into public.leader_commercial_offers (
    lead_id, calculation_id, client_id, order_id, offer_type, title,
    short_text, full_text, total_sum, valid_until, status,
    created_by, updated_by, created_at, updated_at
  ) values (
    v_calculation.lead_id, v_calculation.id, v_calculation.client_id, v_calculation.order_id,
    'Подробное + короткое', v_title, v_short_text, v_full_text,
    v_calculation.client_total, v_valid_until, 'Черновик',
    v_actor_id, v_actor_id, v_now, v_now
  ) returning * into v_offer;

  update public.leader_lead_calculations
  set commercial_offer_id = v_offer.id,
      status = 'КП сформировано',
      updated_by = v_actor_id,
      updated_at = v_now
  where id = v_calculation.id
  returning * into v_calculation;

  update public.leader_leads
  set status = 'Расчёт подготовлен',
      updated_at = v_now
  where id = v_calculation.lead_id
  returning * into v_lead;

  insert into public.leader_commercial_offer_events (
    offer_id, lead_id, calculation_id, event_type, old_status, new_status,
    comment, created_by, created_by_email, created_at
  ) values (
    v_offer.id, v_offer.lead_id, v_offer.calculation_id,
    'offer.created_from_calculation', null, 'Черновик',
    'КП сформировано из сохранённого расчёта',
    v_actor_id, nullif(btrim(v_profile.email), ''), v_now
  ) returning * into v_event;

  v_response := jsonb_build_object(
    'ok', true,
    'request_id', v_request_id,
    'entity', jsonb_build_object(
      'id', v_offer.id,
      'lead_id', v_offer.lead_id,
