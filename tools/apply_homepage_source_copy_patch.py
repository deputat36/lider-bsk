#!/usr/bin/env python3
from pathlib import Path

PAGE = Path('index.html')
text = PAGE.read_text(encoding='utf-8')

replacements = (
    ('заявка сразу попадает в CRM', 'обращение получает номер и не теряется'),
    ('<b>Заявка в CRM</b>', '<b>Обращение под контролем</b>'),
    ('Обращение не теряется в переписке и сразу видно в работе.', 'После отправки вы получаете номер обращения, а специалист видит описание задачи.'),
    ('<b>Контроль расчёта</b>', '<b>Понятный расчёт</b>'),
    ('Сложные заказы можно считать с контролем себестоимости и маржи.', 'До начала работ согласуем вариант, стоимость, сроки и внешний вид.'),
    ('Дизайн, соцсети, контент и карты можно продавать не только в Борисоглебске.', 'Дизайн, соцсети, контент и карты можно заказать из любого города.'),
    ('Опишите задачу в форме. Заявка попадёт в CRM РА «Лидер», после чего мы уточним детали и рассчитаем стоимость.', 'Опишите задачу в форме. После отправки появится номер обращения — мы уточним детали и подготовим расчёт.'),
    ('Работаем с заявками онлайн. Это помогает быстрее принимать обращения, не терять данные и обрабатывать заказы в CRM.', 'Принимаем обращения онлайн: описание задачи и контакты сразу передаются специалисту, чтобы вам не пришлось повторять данные.'),
    ('Главный способ обращения — форма на сайте. Она сразу передает заявку в рабочую CRM.', 'Главный способ обращения — форма на сайте. После отправки вы получите номер обращения для быстрой проверки.'),
)

for old, new in replacements:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f'Expected exactly one source marker, found {count}: {old}')
    text = text.replace(old, new, 1)

for old, _ in replacements:
    if old in text:
        raise SystemExit(f'Stale internal homepage copy remains: {old}')

PAGE.write_text(text, encoding='utf-8')
print(f'Applied {len(replacements)} guarded homepage copy replacements.')
