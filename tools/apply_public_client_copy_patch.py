def main() -> None:
    updated: list[Path] = []
    for path, replacements in REPLACEMENTS.items():
        text = path.read_text(encoding='utf-8')
        for old, new in replacements:
            count = text.count(old)
            if count != 1:
                raise SystemExit(f'{path}: expected exactly one source marker, found {count}: {old}')
            text = text.replace(old, new, 1)
        path.write_text(text, encoding='utf-8')
        updated.append(path)

    for path in updated:
        text = path.read_text(encoding='utf-8').casefold()
        for marker in ('crm', 'себестоим', 'марж'):
            if marker in text:
                raise SystemExit(f'{path}: internal term remains after patch: {marker}')

    print(f'Updated client-facing source copy in {len(updated)} public HTML files.')


if __name__ == '__main__':
    main()
